#!/usr/bin/env python3
"""Vendor identification marks from a pinned theSVG revision for offline use."""
from pathlib import Path
import json
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
REVISION = '5c8bf9e866c44d3361b443d70e503734f3d3f298'
BASE = f'https://raw.githubusercontent.com/glincker/thesvg/{REVISION}'

if __name__ == '__main__':
    folder = ROOT / 'src/assets/brand'
    symbols = {}
    for name in ['spotify', 'bose', 'github']:
        data = urllib.request.urlopen(f'{BASE}/public/icons/{name}/mono.svg', timeout=30).read()
        (folder / f'{name}-mono.svg').write_bytes(data)
        svg = ET.fromstring(data)
        symbols[name] = {
            'viewBox': '0 10 24 4' if name == 'bose' else svg.attrib['viewBox'],
            'paths': [node.attrib['d'] for node in svg.iter() if node.tag.endswith('}path')],
        }
    (ROOT / 'src/components/service-brands.js').write_text(
        '// Generated by scripts/vendor-service-brands.py. Provenance: docs/BRANDING.md.\n'
        'export const serviceBrandIcons=' + json.dumps(symbols) + ';\n'
    )
    trademark = urllib.request.urlopen(f'{BASE}/TRADEMARK.md', timeout=30).read()
    (ROOT / 'LICENSES/theSVG-Trademark.txt').write_bytes(trademark)
    print(f'Vendored Spotify, Bose and GitHub marks: {REVISION}')
