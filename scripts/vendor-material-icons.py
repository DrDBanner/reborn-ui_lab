#!/usr/bin/env python3
"""Vendor the UI's Google Material Symbols Rounded (24px, Apache-2.0).

The pinned upstream revision makes regeneration reviewable and reproducible.
Only trusted upstream path data is emitted; no external SVG markup is injected.
"""
import concurrent.futures
import json
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
REVISION = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7"
BASE = f"https://raw.githubusercontent.com/google/material-design-icons/{REVISION}"
NAMES = """
add add_circle add_link alarm album arrow_back arrow_forward backup bug_report build
cast check check_circle chevron_right close code dark_mode delete desktop_windows
dns dock_to_left do_not_disturb_on download edit expand_less expand_more fast_forward favorite favorite_border
folder graphic_eq grid_view group_add groups help history hub info library_music
light_mode lightbulb menu more_horiz music_cast music_note network_check open_in_new pause pause_circle phone_iphone
play_arrow play_circle push_pin radio restart_alt science search search_off settings
settings_backup_restore skip_next skip_previous speaker speaker_group stop sync
system_update task_alt tune vertical_split volume_up warning wifi
""".split()
ALIASES = {
    "add_circle_outline": "add_circle",
    "delete_outline": "delete",
    "experiment": "science",
    "remove_circle_outline": "do_not_disturb_on",
}


def fetch_icon(name):
    source_name = "favorite" if name == "favorite_border" else name
    filename = "favorite_fill1_24px" if name == "favorite" else f"{source_name}_24px"
    url = f"{BASE}/symbols/web/{source_name}/materialsymbolsrounded/{filename}.svg"
    with urllib.request.urlopen(url, timeout=30) as response:
        svg = ET.fromstring(response.read())
    paths = [element.attrib["d"] for element in svg.iter() if element.tag.endswith("}path")]
    if not paths:
        raise ValueError(f"No paths for {name}")
    viewbox=svg.attrib.get("viewBox")
    if not viewbox:
        width=svg.attrib["width"].removesuffix("px")
        height=svg.attrib["height"].removesuffix("px")
        viewbox=f"0 0 {width} {height}"
    return name, {"viewBox": viewbox, "paths": paths}


if __name__ == "__main__":
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        icons = dict(pool.map(fetch_icon, sorted(NAMES)))
    for alias, name in ALIASES.items():
        icons[alias] = icons[name]
    output = ROOT / "src/components/material-icons.js"
    output.write_text(
        f"// Google Material Symbols Rounded · Apache-2.0 · upstream {REVISION}\n"
        "// Generated by scripts/vendor-material-icons.py. See docs/MATERIAL_ICONS.md.\n"
        "export const materialIcons=" + json.dumps(icons, separators=(",", ":"), sort_keys=True) + ";\n"
    )
    license_dir = ROOT / "LICENSES"
    license_dir.mkdir(exist_ok=True)
    with urllib.request.urlopen(f"{BASE}/LICENSE", timeout=30) as response:
        (license_dir / "material-symbols-Apache-2.0.txt").write_bytes(response.read())
    print(f"Vendored {len(NAMES)} symbols and {len(ALIASES)} aliases into {output}")
